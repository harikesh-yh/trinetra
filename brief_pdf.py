"""PDF brief generator (reportlab).

Turns an answer + cited cases + the SQL run into a downloadable, court-defensible
intelligence brief, including the trust footer (audit reference + disclaimers).
"""
from __future__ import annotations

import io
from datetime import datetime

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import cm
from reportlab.platypus import (Paragraph, SimpleDocTemplate, Spacer, Table,
                                TableStyle)


def build_brief(user, question: str, payload: dict) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, topMargin=2 * cm, bottomMargin=2 * cm)
    styles = getSampleStyleSheet()
    title = ParagraphStyle("title", parent=styles["Title"], fontSize=18,
                           textColor=colors.HexColor("#1a3a5c"))
    h2 = ParagraphStyle("h2", parent=styles["Heading2"], fontSize=12,
                        textColor=colors.HexColor("#1a3a5c"))
    small = ParagraphStyle("small", parent=styles["Normal"], fontSize=8,
                           textColor=colors.grey)

    story = []
    story.append(Paragraph("TRINETRA - Crime Intelligence Brief", title))
    story.append(Spacer(1, 6))
    story.append(Paragraph(
        f"Generated {datetime.now():%Y-%m-%d %H:%M} &bull; User: {user.username} "
        f"&bull; Role: {user.role} &bull; {user.scope_label}", small))
    story.append(Spacer(1, 14))

    story.append(Paragraph("Query", h2))
    story.append(Paragraph(question, styles["Normal"]))
    story.append(Spacer(1, 10))

    story.append(Paragraph("Finding", h2))
    story.append(Paragraph(payload.get("answer", "(no answer)"), styles["Normal"]))
    conf = payload.get("confidence")
    if conf:
        story.append(Spacer(1, 4))
        story.append(Paragraph(f"Confidence: {conf['level']} - {conf['caveat']}", small))
    story.append(Spacer(1, 10))

    if payload.get("sql"):
        story.append(Paragraph("Query executed (explainability)", h2))
        story.append(Paragraph(f"<font face='Courier' size=8>{payload['sql']}</font>",
                               styles["Normal"]))
        story.append(Spacer(1, 10))

    rows = payload.get("rows") or payload.get("results") or []
    if rows:
        story.append(Paragraph("Cited records", h2))
        cols = payload.get("columns") or list(rows[0].keys())[:5]
        data = [cols]
        for r in rows[:20]:
            data.append([str(r.get(c, ""))[:40] for c in cols])
        tbl = Table(data, repeatRows=1)
        tbl.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1a3a5c")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTSIZE", (0, 0), (-1, -1), 7),
            ("GRID", (0, 0), (-1, -1), 0.25, colors.grey),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#eef3f8")]),
        ]))
        story.append(tbl)
        story.append(Spacer(1, 10))

    cited = payload.get("cited_ids")
    if cited:
        story.append(Paragraph(
            "Source FIR CaseMasterIDs: " + ", ".join(str(c) for c in cited[:50]), small))
        story.append(Spacer(1, 8))

    story.append(Spacer(1, 14))
    story.append(Paragraph(
        "Trust &amp; audit: This brief was generated by TRINETRA. The query above was "
        "logged to the audit trail with the requesting user, role and scope. Accused "
        "individuals are presumed innocent until proven guilty. Demographic insights, "
        "if any, are victimization patterns only and must not be used for profiling.",
        small))

    doc.build(story)
    return buf.getvalue()
